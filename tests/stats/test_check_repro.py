def test_check_repro_match_with_fake_regenerator(tmp_path: pathlib.Path) -> None:
    benchmarks = ("01-short-factual",)
    results_dir = tmp_path / "results"
    _seed_committed(results_dir, benchmarks, payload='{"ok":true}\n')

    seen: dict[str, object] = {}

    def fake_regenerate(bms, *, benchmarks_dir, pricing_dir, output_dir):
        seen["benchmarks_dir"] = benchmarks_dir
        seen["pricing_dir"] = pricing_dir
        # Faithful regenerator: reproduce the committed bytes exactly.
        _seed_committed(output_dir, bms, payload='{"ok":true}\n')

    outcome = cr.check_repro(
        benchmarks,
        benchmarks_dir=tmp_path / "benchmarks",
        pricing_dir=tmp_path / "pricing",
        results_dir=results_dir,
        regenerate=fake_regenerate,
        tmp_root=tmp_path,
        cleanup=True,
    )
    assert outcome.ok
    assert outcome.tmp_dir is None  # cleaned up
    # Canonical input dirs were forwarded unchanged.
    assert seen["benchmarks_dir"] == tmp_path / "benchmarks"
    assert seen["pricing_dir"] == tmp_path / "pricing"


def test_check_repro_mismatch_with_fake_regenerator(tmp_path: pathlib.Path) -> None:
    benchmarks = ("01-short-factual",)
    results_dir = tmp_path / "results"
    _seed_committed(results_dir, benchmarks, payload='{"ok":true}\n')

    def drifting_regenerate(bms, *, benchmarks_dir, pricing_dir, output_dir):
        _seed_committed(output_dir, bms, payload='{"ok":true}\n')
        _write(
            output_dir / "01-short-factual" / "inter_rater.json",
            '{"ok":false}\n',
        )

    outcome = cr.check_repro(
        benchmarks,
        benchmarks_dir=tmp_path / "benchmarks",
        pricing_dir=tmp_path / "pricing",
        results_dir=results_dir,
        regenerate=drifting_regenerate,
        tmp_root=tmp_path,
        cleanup=True,
    )
    assert not outcome.ok
    bad = [r for r in outcome.results if not r.ok]
    assert [r.artifact for r in bad] == ["inter_rater.json"]


def test_check_repro_preseeds_into_tmp(tmp_path: pathlib.Path) -> None:
    benchmarks = ("01-short-factual",)
    results_dir = tmp_path / "results"
    _seed_committed(results_dir, benchmarks, payload='{}\n')
    _write(
        results_dir / "01-short-factual" / cr.MANUAL_SPOT_CHECKS,
        '{"scores":[{"sample_id":"s","model":"m","effort":"low","repeat":0,"score":1}]}\n',
    )

    captured: dict[str, pathlib.Path] = {}

    def regen(bms, *, benchmarks_dir, pricing_dir, output_dir):
        captured["output_dir"] = output_dir
        # Manual scores must already be present at regenerate time.
        seeded_file = output_dir / "01-short-factual" / cr.MANUAL_SPOT_CHECKS
        assert seeded_file.is_file()
        _seed_committed(output_dir, bms, payload='{}\n')

    outcome = cr.check_repro(
        benchmarks,
        benchmarks_dir=tmp_path / "benchmarks",
        pricing_dir=tmp_path / "pricing",
        results_dir=results_dir,
        regenerate=regen,
        tmp_root=tmp_path,
        cleanup=False,
    )
    assert outcome.seeded_benchmarks == ["01-short-factual"]
    assert outcome.ok


def test_check_repro_manual_found_paths_root_invariant(
    tmp_path: pathlib.Path,
) -> None:
    """Pre-seeded manual scores must not break the byte-compare via tmp paths.

    Regression for T-064: the committed ``inter_rater.json`` is generated with
    ``--output-dir results/supplementary`` so it records the manual source as a
    repo-relative ``results/supplementary/<b>/manual_spot_checks.json``. The
    repro check pre-seeds that committed file into a *system tmp* output_dir and
    regenerates. The regenerated ``found_paths`` must record the same logical
    path (not an absolute ``/tmp/...`` path), so the byte comparison matches.

    The injected regenerator builds ``found_paths`` through the real
    :func:`inter_rater._load_manual_scores`, so this exercises the actual path
    normalization rather than a stand-in.
    """
    benchmark = "01-short-factual"
    # results_dir lives outside REPO_ROOT (a tmp tree), mirroring how the real
    # check_repro committed copy + tmp regeneration both sit outside the repo.
    results_dir = tmp_path / "results" / "supplementary"
    benchmarks_dir = tmp_path / "benchmarks"  # no committed manual inputs here
    manual_payload = json.dumps(
        [{"sample_id": "s1", "model": "gpt-5.2", "effort": "low",
          "repeat": 0, "reviewer_score": 2}]
    )
    _write(results_dir / benchmark / cr.MANUAL_SPOT_CHECKS, manual_payload)

    def make_inter_rater(output_dir: pathlib.Path) -> str:
        _, found, _ = ir._load_manual_scores(
            benchmark,
            benchmarks_dir=benchmarks_dir,
            output_dir=output_dir,
        )
        payload = {"manual_spot_checks": {"found_paths": sorted(found)}}
        return json.dumps(payload, indent=2, sort_keys=True) + "\n"

    # Committed artifacts: inter_rater.json generated as if output_dir == the
    # canonical results/supplementary root (the manual file lives under it).
    _write(results_dir / benchmark / "bootstrap_ci.json", "{}\n")
    _write(results_dir / benchmark / "cohens_d.json", "{}\n")
    _write(
        results_dir / benchmark / "inter_rater.json",
        make_inter_rater(results_dir),
    )

    def regen(bms, *, benchmarks_dir, pricing_dir, output_dir):
        # The pre-seed must have placed the manual file under the tmp output.
        seeded = output_dir / benchmark / cr.MANUAL_SPOT_CHECKS
        assert seeded.is_file()
        _write(output_dir / benchmark / "bootstrap_ci.json", "{}\n")
        _write(output_dir / benchmark / "cohens_d.json", "{}\n")
        _write(
            output_dir / benchmark / "inter_rater.json",
            make_inter_rater(output_dir),
        )

    outcome = cr.check_repro(
        (benchmark,),
        benchmarks_dir=benchmarks_dir,
        pricing_dir=tmp_path / "pricing",
        results_dir=results_dir,
        regenerate=regen,
        tmp_root=tmp_path,
        cleanup=True,
    )
    assert outcome.seeded_benchmarks == [benchmark]
    by_name = {r.artifact: r.status for r in outcome.results}
    assert by_name["inter_rater.json"] == "match"
    assert outcome.ok


