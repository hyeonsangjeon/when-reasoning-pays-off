def test_compare_all_match(tmp_path: pathlib.Path) -> None:
    benchmarks = ("01-short-factual",)
    committed = tmp_path / "committed"
    regen = tmp_path / "regen"
    _seed_committed(committed, benchmarks, payload='{"a":1}\n')
    _seed_committed(regen, benchmarks, payload='{"a":1}\n')

    results = cr.compare_artifacts(
        benchmarks, ARTIFACTS, committed_dir=committed, regenerated_dir=regen
    )
    assert len(results) == len(ARTIFACTS)
    assert all(r.ok for r in results)
    assert {r.status for r in results} == {"match"}


def test_compare_detects_perturbed_artifact(tmp_path: pathlib.Path) -> None:
    benchmarks = ("01-short-factual",)
    committed = tmp_path / "committed"
    regen = tmp_path / "regen"
    _seed_committed(committed, benchmarks, payload='{"a":1}\n')
    _seed_committed(regen, benchmarks, payload='{"a":1}\n')
    # Perturb a single regenerated byte.
    _write(regen / "01-short-factual" / "cohens_d.json", '{"a":2}\n')

    results = cr.compare_artifacts(
        benchmarks, ARTIFACTS, committed_dir=committed, regenerated_dir=regen
    )
    differing = [r for r in results if not r.ok]
    assert len(differing) == 1
    assert differing[0].artifact == "cohens_d.json"
    assert differing[0].status == "differ"


