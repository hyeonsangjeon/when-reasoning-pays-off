"""Unit tests for ``scripts/stats/check_repro.py`` (D-011 Invariant 2, T-064).

These are pure tests over tiny synthetic trees. They exercise the wrapper's
comparison, manual spot-check pre-seed, results-tree dirt guard, and end-to-end
orchestration via an **injected fake regenerator** — they never run the real
bootstrap (the live byte-for-byte run is the `python scripts/stats/check_repro.py`
validation command, not a unit test).
"""

from __future__ import annotations

import json
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from scripts.stats import check_repro as cr  # noqa: E402
from scripts.stats import inter_rater as ir  # noqa: E402

ARTIFACTS = cr.ARTIFACTS


def _write(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _seed_committed(root: pathlib.Path, benchmarks, payload="{}\n") -> None:
    for b in benchmarks:
        for name in ARTIFACTS:
            _write(root / b / name, payload)


